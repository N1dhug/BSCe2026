"""F2-I stochastic BM1 price optimization reference.

A non-trivial target is generated by the deterministic F1-D two-price benchmark.
The stochastic problem then starts from Beta(20,20) and minimizes the F2-H
expected squared tracking cost.

Primary optimizer:
    bounded multistart Powell on the pure-FV stochastic objective.

Secondary optimizer-model check:
    bounded Powell on an M=30 dynamic Beta-mixture surrogate.

Final validation:
    deterministic reference prices, FV optimum and mixture optimum are evaluated
    with pure FV, high-resolution mixtures and Monte Carlo using common initial
    samples and common Brownian increments.

Run from the repository root:

    python -B -m src.exe.run_model.bm_1.stochastic_optimization_reference
"""

