T = (0.0, 1.0)
INTERVAL_EDGES = np.array([0.0, 0.5, 1.0], dtype=float)
KNOWN_DETERMINISTIC_PRICES = np.array([0.72, 0.28], dtype=float)
INITIAL_PRICES = np.array([0.55, 0.45], dtype=float)

BASELINE = 0.3
X0_DETERMINISTIC = 0.5
C = 1.0
K = 2.0
XI = 1.0

FV_X_STEPS = 201
MIXTURE_OPT_X_STEPS = 81
FINAL_MIXTURE_X_STEPS = 201
MIXTURE_OPT_DEGREE = 30
FINAL_MIXTURE_DEGREES = (30, 38)

OBJECTIVE_MAX_STEP = 1.0 / 96.0
SOLVER_MAX_STEP = 1.0 / 96.0
TARGET_T_STEPS = 1537
COARSE_VALUES = np.linspace(0.0, 1.0, 5)
N_COARSE_STARTS = 4

MC_PATHS = 50_000
MC_INITIAL_SEED = 2033
MC_BROWNIAN_SEED = 2034


@dataclass(frozen=True)
class MonteCarloCandidateResult:
    """MC objective for one candidate plus shared pathwise costs."""

    prices: np.ndarray
    objective: object
    diagnostics: dict


def linear_state_response(x):
    return 1.0 - 2.0 * np.asarray(x, dtype=float)


def linear_price_response(u):
    return 1.0 - 2.0 * np.asarray(u, dtype=float)


def _baseline():
    return input_builder.energy(
        (np.array(T), np.array([BASELINE, BASELINE]))
    )


def _parameter_template():
    placeholder = input_builder.price_intervals(
        (INTERVAL_EDGES, INITIAL_PRICES)
    )
    return [
        placeholder,
        linear_state_response,
        linear_price_response,
        C,
        K,
        XI,
    ]


def _parameters_for_prices(prices):
    parameters = _parameter_template()
    parameters[0] = input_builder.price_intervals(
        (INTERVAL_EDGES, np.asarray(prices, dtype=float))
    )
    return parameters


def build_deterministic_target():
    """Return the F1-D target demand as a breakpoint-aware callable."""
    baseline = _baseline()
    generator = bm_1(baseline, baseline, T, TARGET_T_STEPS)
    target_t = np.linspace(T[0], T[1], TARGET_T_STEPS)

    result = generator.deterministic_solver(
        [X0_DETERMINISTIC],
        _parameters_for_prices(KNOWN_DETERMINISTIC_PRICES),
        t_eval=target_t,
        breakpoints=INTERVAL_EDGES[1:-1],
        rtol=1.0e-10,
        atol=1.0e-12,
        max_step=1.0 / (TARGET_T_STEPS - 1),
    )
    target_demand = np.asarray(result[7], dtype=float)

    breakpoint = INTERVAL_EDGES[1]
    left_mask = target_t < breakpoint
    right_mask = target_t >= breakpoint
    left = PchipInterpolator(
        target_t[left_mask],
        target_demand[left_mask],
        extrapolate=True,
    )
    right = PchipInterpolator(
        target_t[right_mask],
        target_demand[right_mask],
        extrapolate=True,
    )

    def target(query):
        array = np.asarray(query, dtype=float)
        values = np.where(
            array < breakpoint,
            left(array),
            right(array),
        )
        return float(values) if array.ndim == 0 else values

    return target, target_t, target_demand


def build_stochastic_model(target, t_steps=2):
    baseline = _baseline()
    return bm_1(baseline, target, T, t_steps)


def _initial_mass(model, x_steps):
    edges, _, _ = model.fokker_planc_reference.grid(x_steps)
    return beta_initial_cell_mass(
        edges,
        alpha=INITIAL_ALPHA,
        beta=INITIAL_BETA,
    )


def _build_fv_evaluator(
    model,
    *,
    x_steps,
    objective_max_step,
    solver_max_step,
):
    initial_mass = _initial_mass(model, x_steps)
    return FVStochasticPriceEvaluator(
        model,
        _parameter_template(),
        INTERVAL_EDGES,
        SIGMA_X,
        initial_mass,
        objective_max_step=objective_max_step,
        solver_max_step=solver_max_step,
    )


def _combine_starts(*groups):
    rows = []
    for group in groups:
        array = np.asarray(group, dtype=float)
        if array.ndim == 1:
            array = array[None, :]
        for row in array:
            if not any(np.array_equal(row, previous) for previous in rows):
                rows.append(row.copy())
    return np.asarray(rows, dtype=float)


def evaluate_mc_candidates_common_random_numbers(
    evaluator,
    candidates,
    *,
    n_paths,
    initial_seed,
    brownian_seed,
):
    """Evaluate candidate prices with shared initial states and Wiener paths."""
    model = evaluator.model
    initial_states = sample_beta_initial_states(
        n_paths,
        initial_seed,
        alpha=INITIAL_ALPHA,
        beta=INITIAL_BETA,
    )
    integration_t, _ = model.euler_maruyama.build_time_grid(
        evaluator.solver_t_eval,
        breakpoints=evaluator.breakpoints,
        max_step=evaluator.solver_max_step,
    )
    dW = model.euler_maruyama.brownian_increments(
        integration_t,
        n_paths=n_paths,
        seed=brownian_seed,
    )

    results = {}
    for name, prices in candidates.items():
        parameters = evaluator.parameters_for_prices(prices)
        output = model.euler_maruyama_solver(
            initial_states,
            parameters,
            evaluator.sigma_x,
            n_paths=n_paths,
            boundary="none",
            t_eval=evaluator.solver_t_eval,
            breakpoints=evaluator.breakpoints,
            max_step=evaluator.solver_max_step,
            brownian_increments=dW,
            return_diagnostics=True,
        )
        _, _, _, _, _, _, _, demand, diagnostics = output
        if diagnostics["total_violations"]:
            raise RuntimeError(
                f"MC validation for {name} produced raw boundary violations."
            )

        midpoint_demand = np.asarray(demand, dtype=float)[:, 1:-1]
        objective = monte_carlo_tracking_objective(
            evaluator.widths,
            midpoint_demand,
            evaluator.target,
        )
        results[name] = MonteCarloCandidateResult(
            prices=np.asarray(prices, dtype=float).copy(),
            objective=objective,
            diagnostics=dict(diagnostics),
        )

    return results


def paired_mc_improvement(reference, candidate):
    """Return mean and SE of pathwise J_reference - J_candidate."""
    difference = (
        np.asarray(reference.objective.path_objectives, dtype=float)
        - np.asarray(candidate.objective.path_objectives, dtype=float)
    )
    return (
        float(np.mean(difference)),
        float(np.std(difference, ddof=1) / np.sqrt(difference.size)),
    )


def run_optimization_reference(
    *,
    fv_x_steps=FV_X_STEPS,
    mixture_opt_x_steps=MIXTURE_OPT_X_STEPS,
    final_mixture_x_steps=FINAL_MIXTURE_X_STEPS,
    objective_max_step=OBJECTIVE_MAX_STEP,
    solver_max_step=SOLVER_MAX_STEP,
    coarse_values=COARSE_VALUES,
    n_coarse_starts=N_COARSE_STARTS,
    optimize_mixture=True,
    validate_mc=True,
    mc_paths=MC_PATHS,
    progress=None,
):
    """Run the complete F2-I reference workflow."""
    def report(message):
        if progress is not None:
            progress(message)

    report("[1/6] Building deterministic target and FV objective surface")
    target, target_t, target_demand = build_deterministic_target()
    model = build_stochastic_model(target)

    fv = _build_fv_evaluator(
        model,
        x_steps=fv_x_steps,
        objective_max_step=objective_max_step,
        solver_max_step=solver_max_step,
    )

    coarse_values = np.asarray(coarse_values, dtype=float)
    surface = coarse_price_surface(fv, coarse_values)
    surface_starts = best_surface_starts(
        coarse_values,
        surface,
        n_coarse_starts,
    )
    fv_starts = _combine_starts(
        surface_starts,
        KNOWN_DETERMINISTIC_PRICES,
        INITIAL_PRICES,
    )
    report("[2/6] Pure-FV multistart Powell optimization")
    fv_optimization = multistart_powell(
        fv,
        fv_starts,
        progress=progress,
        options={
            "xtol": 2.0e-5,
            "ftol": 1.0e-9,
            "maxiter": 100,
        },
    )
    fv_prices = np.asarray(fv_optimization.best.x, dtype=float)

    report("[3/6] Dynamic-mixture optimizer-model comparison")
    if optimize_mixture:
        mixture_support = _build_fv_evaluator(
            model,
            x_steps=mixture_opt_x_steps,
            objective_max_step=objective_max_step,
            solver_max_step=solver_max_step,
        )
        mixture_optimizer = DynamicMixturePriceEvaluator(
            mixture_support,
            MIXTURE_OPT_DEGREE,
            cfl=DEFAULT_CFL,
        )
        mixture_starts = _combine_starts(
            fv_prices,
            KNOWN_DETERMINISTIC_PRICES,
        )
        mixture_optimization = multistart_powell(
            mixture_optimizer,
            mixture_starts,
            progress=progress,
            options={
                "xtol": 1.0e-3,
                "ftol": 1.0e-5,
                "maxiter": 30,
            },
        )
        mixture_prices = np.asarray(
            mixture_optimization.best.x,
            dtype=float,
        )
    else:
        mixture_optimizer = None
        mixture_optimization = None
        mixture_prices = fv_prices.copy()

    candidates = {
        "deterministic_reference": KNOWN_DETERMINISTIC_PRICES.copy(),
        "fv_optimum": fv_prices.copy(),
        "mixture_optimum": mixture_prices.copy(),
    }

    report("[4/6] Reevaluating candidates with pure FV")
    fv_evaluations = {
        name: fv.evaluate(prices)
        for name, prices in candidates.items()
    }

    report("[5/6] High-resolution mixture reevaluations")
    final_mixture = {}
    for degree in FINAL_MIXTURE_DEGREES:
        support = _build_fv_evaluator(
            model,
            x_steps=final_mixture_x_steps,
            objective_max_step=objective_max_step,
            solver_max_step=solver_max_step,
        )
        evaluator = DynamicMixturePriceEvaluator(
            support,
            degree,
            cfl=DEFAULT_CFL,
        )
        final_mixture[degree] = {
            name: evaluator.evaluate(prices)
            for name, prices in candidates.items()
        }

    report("[6/6] Paired Monte Carlo validation")
    mc = None
    paired = None
    if validate_mc:
        mc = evaluate_mc_candidates_common_random_numbers(
            fv,
            candidates,
            n_paths=mc_paths,
            initial_seed=MC_INITIAL_SEED,
            brownian_seed=MC_BROWNIAN_SEED,
        )
        reference = mc["deterministic_reference"]
        paired = {
            name: paired_mc_improvement(reference, item)
            for name, item in mc.items()
            if name != "deterministic_reference"
        }

    return {
        "target_t": target_t,
        "target_demand_dense": target_demand,
        "model": model,
        "fv_evaluator": fv,
        "coarse_values": coarse_values,
        "coarse_surface": surface,
        "fv_starts": fv_starts,
        "fv_optimization": fv_optimization,
        "mixture_optimizer": mixture_optimizer,
        "mixture_optimization": mixture_optimization,
        "candidates": candidates,
        "fv_evaluations": fv_evaluations,
        "final_mixture": final_mixture,
        "mc": mc,
        "paired_mc_improvement": paired,
    }


def _format_prices(prices):
    return np.array2string(
        np.asarray(prices, dtype=float),
        precision=6,
        floatmode="fixed",
    )


def main():
    result = run_optimization_reference(
        progress=lambda message: print(message, flush=True)
    )

    print("F2-I stochastic BM1 price optimization")
    print("--------------------------------------")
    print(
        "Deterministic reference prices: "
        + _format_prices(KNOWN_DETERMINISTIC_PRICES)
    )
    print(
        "FV stochastic optimum:          "
        + _format_prices(result["candidates"]["fv_optimum"])
    )
    print(
        "Mixture stochastic optimum:     "
        + _format_prices(result["candidates"]["mixture_optimum"])
    )
    print()

    fv_opt = result["fv_optimization"]
    print("FV bounded Powell multistart")
    print("----------------------------")
    print(f"starts: {len(fv_opt.results)}")
    print(
        "successful: "
        f"{sum(bool(item.success) for item in fv_opt.results)}"
    )
    print(
        f"best objective: {float(fv_opt.best.fun):.8e}, "
        f"iterations/evaluations: "
        f"{fv_opt.best.nit}/{fv_opt.best.nfev}"
    )
    successful_costs = [float(item.fun) for item in fv_opt.results if item.success]
    print(f"successful-start objective spread: {np.ptp(successful_costs):.3e}")
    print(f"actual solves/cache hits: {fv_opt.objective_evaluations}/{fv_opt.cache_hits}")
    print()

    if result["mixture_optimization"] is not None:
        mix_opt = result["mixture_optimization"]
        print(f"M={MIXTURE_OPT_DEGREE} mixture Powell multistart")
        print("--------------------------------")
        print(f"starts: {len(mix_opt.results)}")
        print(
            "successful: "
            f"{sum(bool(item.success) for item in mix_opt.results)}"
        )
        print(
            f"best surrogate objective: {float(mix_opt.best.fun):.8e}, "
            f"iterations/evaluations: "
            f"{mix_opt.best.nit}/{mix_opt.best.nfev}"
        )
        print()

    print("Pure-FV reevaluation")
    print("--------------------")
    reference_fv = result["fv_evaluations"]["deterministic_reference"]
    for name, item in result["fv_evaluations"].items():
        improvement = (
            reference_fv.objective.total - item.objective.total
        )
        print(
            f"{name:24s} J={item.objective.total:.8e}, "
            f"bias={item.objective.bias:.8e}, "
            f"variance={item.objective.variance:.8e}, "
            f"improvement={improvement:.6e}"
        )

    print()
    print("High-resolution mixture reevaluation")
    print("------------------------------------")
    for degree, evaluations in result["final_mixture"].items():
        print(f"M={degree}")
        for name, item in evaluations.items():
            print(
                f"  {name:22s} J={item.objective.total:.8e}, "
                f"bias={item.objective.bias:.8e}, "
                f"variance={item.objective.variance:.8e}"
            )

    if result["mc"] is not None:
        print()
        print("Monte Carlo common-random-number validation")
        print("-------------------------------------------")
        for name, item in result["mc"].items():
            objective = item.objective
            print(
                f"{name:24s} J={objective.objective.total:.8e}, "
                f"SE={objective.standard_error:.3e}"
            )
        print()
        print("Paired MC improvement over deterministic reference")
        print("--------------------------------------------------")
        for name, (improvement, standard_error) in (
            result["paired_mc_improvement"].items()
        ):
            z = (
                improvement / standard_error
                if standard_error > 0.0
                else np.inf
            )
            print(
                f"{name:24s} improvement={improvement:.6e}, "
                f"SE={standard_error:.3e}, ratio={z:.3f}"
            )

    fv = result["fv_evaluator"]
    hours = 24.0 * fv.midpoints
    fig, axes = plt.subplots(2, 2, figsize=(13, 10))
    ax_surface, ax_demand, ax_price, ax_parts = axes.ravel()

    grid_first, grid_second = np.meshgrid(
        result["coarse_values"],
        result["coarse_values"],
        indexing="ij",
    )
    contour = ax_surface.contourf(
        grid_first,
        grid_second,
        result["coarse_surface"],
        levels=15,
    )
    fig.colorbar(contour, ax=ax_surface, label="FV stochastic objective")
    for name, marker in (
        ("deterministic_reference", "o"),
        ("fv_optimum", "x"),
        ("mixture_optimum", "+"),
    ):
        prices = result["candidates"][name]
        ax_surface.scatter(
            prices[0],
            prices[1],
            marker=marker,
            s=90,
            label=name.replace("_", " "),
        )
    ax_surface.set_xlabel("First-half price")
    ax_surface.set_ylabel("Second-half price")
    ax_surface.set_title("Coarse stochastic objective surface")
    ax_surface.legend(loc="best")

    ax_demand.plot(
        hours,
        fv.target,
        linewidth=2.5,
        label="Target A(t)",
    )
    for name, item in result["fv_evaluations"].items():
        ax_demand.plot(
            hours,
            item.objective.expected_demand,
            label=name.replace("_", " "),
        )
    ax_demand.set_xlabel("Time [h]")
    ax_demand.set_ylabel("Expected demand")
    ax_demand.set_title("Pure-FV expected demand")
    ax_demand.grid(True)
    ax_demand.legend(loc="best")

    for name, prices in result["candidates"].items():
        price = input_builder.price_intervals(
            (INTERVAL_EDGES, prices)
        )
        ax_price.step(
            hours,
            price(fv.midpoints),
            where="mid",
            label=name.replace("_", " "),
        )
    ax_price.set_xlabel("Time [h]")
    ax_price.set_ylabel("Normalized price")
    ax_price.set_ylim(0.0, 1.0)
    ax_price.set_title("Candidate dynamic prices")
    ax_price.grid(True)
    ax_price.legend(loc="best")

    labels = [
        "deterministic\nreference",
        "FV\noptimum",
        "mixture\noptimum",
    ]
    names = [
        "deterministic_reference",
        "fv_optimum",
        "mixture_optimum",
    ]
    bias = [
        result["fv_evaluations"][name].objective.bias
        for name in names
    ]
    variance = [
        result["fv_evaluations"][name].objective.variance
        for name in names
    ]
    positions = np.arange(len(names))
    ax_parts.bar(positions, bias, label="Bias-squared")
    ax_parts.bar(
        positions,
        variance,
        bottom=bias,
        label="Demand variance",
    )
    ax_parts.set_xticks(positions, labels)
    ax_parts.set_ylabel("Pure-FV stochastic objective")
    ax_parts.set_title("Objective decomposition")
    ax_parts.grid(True, axis="y")
    ax_parts.legend(loc="best")

    fig.tight_layout()
    graph_dir = (
        Path(__file__).resolve().parents[4]
        / "files"
        / "output"
        / "graphs"
        / "bm_1"
    )
    graph_dir.mkdir(parents=True, exist_ok=True)
    graph_path = graph_dir / "bm_1_stochastic_optimization_reference.png"
    fig.savefig(graph_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print()
    print(f"Saved graph to {graph_path}")


if __name__ == "__main__":
    main()
