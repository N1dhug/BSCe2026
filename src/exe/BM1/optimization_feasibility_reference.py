"""Reference verification for deterministic BM1 target feasibility (F1-E).

The script separates physical infeasibility from optimizer failure with two
optimizer-independent certificates:

1. a state-feasible target that requires a held price below the admissible
   lower bound, and
2. a constant target whose cumulative energy would exceed state capacity.

Run this module from the repository root:

    python -B -m src.exe.BM1.optimization_feasibility_reference
"""

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from scipy.integrate import simpson

from src.exe.tool.InputBuilder import InputBuilder
from src.model.BM1 import BM1


T = (0.0, 1.0)
X0 = 0.5
BASELINE = 0.3
C = 1.0
K = 2.0
XI = 1.0

OBJECTIVE_T = np.linspace(T[0], T[1], 385)
FINE_T = np.linspace(T[0], T[1], 1537)
RTOL = 1.0e-9
ATOL = 1.0e-11
FINE_RTOL = 1.0e-10
FINE_ATOL = 1.0e-12

# Case 1: the target is generated analytically by a constant price below the
# admissible interval.  The invalid price is never passed to BM1/InputBuilder.
REQUIRED_PRICE = -0.05
PRICE_EDGES = np.array(T, dtype=float)
PRICE_STARTS = (
    np.array([0.0]),
    np.array([0.05]),
    np.array([0.25]),
    np.array([0.50]),
    np.array([0.95]),
)

# Case 2: this normalized demand would require X(1) = 1.02.
CAPACITY_TARGET = 0.82
CAPACITY_EDGES = np.linspace(T[0], T[1], 5)
CAPACITY_STARTS = tuple(
    np.full(CAPACITY_EDGES.size - 1, value)
    for value in (0.05, 0.25, 0.50, 0.75)
) + (
    np.array([0.05, 0.95, 0.05, 0.95]),
    np.array([0.95, 0.05, 0.95, 0.05]),
)


def linear_state_response(x):
    """Return the benchmark response f(x) = 1 - 2x."""
    return 1.0 - 2.0 * np.asarray(x, dtype=float)


def linear_price_response(u):
    """Return the benchmark response g(u) = 1 - 2u."""
    return 1.0 - 2.0 * np.asarray(u, dtype=float)


def as_scalar_if_needed(query, values):
    """Preserve scalar calls while supporting arbitrary NumPy query shapes."""
    return float(values) if np.asarray(query).ndim == 0 else values


def build_baseline():
    """Return the constant normalized baseline used by the benchmark."""
    return InputBuilder.energy(
        (np.array(T, dtype=float), np.array([BASELINE, BASELINE], dtype=float))
    )


def build_parameters(price):
    """Return the standard deterministic BM1 parameter vector."""
    return [
        price,
        linear_state_response,
        linear_price_response,
        C,
        K,
        XI,
    ]


def price_bound_target_state(t):
    """Return the exact state generated by the extended price -0.05.

    The formula is used only to construct and diagnose the target.  It does
    not relax the optimizer's admissible price bounds.
    """
    query = np.asarray(t, dtype=float)
    equilibrium = 1.0 - REQUIRED_PRICE
    rate = K * XI * (1.0 - BASELINE) / C
    state = equilibrium + np.arcsinh(
        np.sinh(K * (X0 - equilibrium))
        * np.exp(-rate * (query - T[0]))
    ) / K
    return as_scalar_if_needed(query, state)


def price_bound_target(t):
    """Return the demand target associated with the extended negative price."""
    query = np.asarray(t, dtype=float)
    state = np.asarray(price_bound_target_state(query), dtype=float)
    delta = np.tanh(K * (1.0 - state - REQUIRED_PRICE))
    demand = BASELINE + XI * (1.0 - BASELINE) * delta
    return as_scalar_if_needed(query, demand)


def capacity_target(t):
    """Return the constant capacity-stress demand target."""
    query = np.asarray(t, dtype=float)
    demand = np.full_like(query, CAPACITY_TARGET, dtype=float)
    return as_scalar_if_needed(query, demand)


def target_implied_state(t, demand):
    """Return the exact implied state for a constant demand and baseline."""
    query = np.asarray(t, dtype=float)
    state = X0 + (demand - BASELINE) * (query - T[0]) / C
    return as_scalar_if_needed(query, state)


def benchmark_required_price(state, demand):
    """Invert the linear benchmark responses to obtain the required price."""
    state = np.asarray(state, dtype=float)
    demand = np.asarray(demand, dtype=float)

    positive = demand >= BASELINE
    delta = np.empty_like(demand)
    delta[positive] = (
        (demand[positive] - BASELINE) / (XI * (1.0 - BASELINE))
    )
    delta[~positive] = (
        (demand[~positive] - BASELINE) / (XI * BASELINE)
    )
    if np.any(np.abs(delta) >= 1.0):
        raise ValueError("Target demand requires |delta| >= 1.")

    return 1.0 - state - np.arctanh(delta) / K


def benchmark_demand_envelope(state):
    """Return attainable demand bounds at a given state for U in [0, 1]."""
    state = np.asarray(state, dtype=float)
    minimum = BASELINE * (1.0 - XI * np.tanh(K * state))
    maximum = BASELINE + XI * (1.0 - BASELINE) * np.tanh(
        K * (1.0 - state)
    )
    return minimum, maximum


def solve_prices(
    model,
    interval_edges,
    prices,
    t_eval,
    rtol,
    atol,
    max_step=np.inf,
):
    """Solve BM1 for an admissible held-price vector."""
    price = InputBuilder.price_intervals((interval_edges, prices))
    return model.deterministic_solver(
        [X0],
        build_parameters(price),
        t_eval=t_eval,
        breakpoints=interval_edges[1:-1],
        rtol=rtol,
        atol=atol,
        max_step=max_step,
    )


def tracking_objective(t, demand, target):
    """Return the integrated squared tracking error."""
    return float(simpson(np.square(demand - target), x=t))


def optimize_from_starts(model, interval_edges, starts):
    """Run identical bounded optimizations from several starting prices."""
    placeholder = InputBuilder.price_intervals(
        (np.array(T, dtype=float), np.array([0.5], dtype=float))
    )
    parameters = build_parameters(placeholder)
    results = []

    for initial_prices in starts:
        results.append(
            model.optimize(
                initial_prices,
                [X0],
                parameters,
                interval_edges=interval_edges,
                t_eval=OBJECTIVE_T,
                rtol=RTOL,
                atol=ATOL,
                options={
                    "ftol": 1.0e-14,
                    "gtol": 1.0e-8,
                    "maxiter": 300,
                },
            )
        )
    return results


def best_result(results):
    """Return the successful result with the smallest objective."""
    successful = [result for result in results if result.success]
    if not successful:
        raise RuntimeError("Every F1-E optimization start failed.")
    return min(successful, key=lambda result: result.fun)


def save_figure(
    price_result,
    price_state,
    price_demand,
    required_price,
    capacity_state,
    capacity_demand,
    capacity_required_state,
):
    """Save target, feasibility-certificate, and best-achieved trajectories."""
    hours = 24.0 * OBJECTIVE_T
    price_target = np.asarray(price_bound_target(OBJECTIVE_T), dtype=float)
    price_target_state = np.asarray(
        price_bound_target_state(OBJECTIVE_T), dtype=float
    )
    capacity_values = np.asarray(capacity_target(OBJECTIVE_T), dtype=float)

    fig, axes = plt.subplots(2, 2, figsize=(12, 9), sharex=True)

    axes[0, 0].plot(hours, price_target, linewidth=2.5, label="Target A(t)")
    axes[0, 0].plot(
        hours,
        price_demand,
        linestyle="--",
        label="Best admissible demand",
    )
    axes[0, 0].set_title("Price-bound certificate")
    axes[0, 0].set_ylabel("Normalized demand")
    axes[0, 0].grid(True)
    axes[0, 0].legend(loc="best")

    axes[0, 1].plot(
        hours,
        required_price,
        linewidth=2.5,
        label="Required held price",
    )
    axes[0, 1].step(
        hours,
        np.full_like(OBJECTIVE_T, price_result.x[0]),
        where="post",
        linestyle="--",
        label="Best admissible price",
    )
    axes[0, 1].axhspan(0.0, 1.0, color="green", alpha=0.08)
    axes[0, 1].axhline(0.0, color="black", linewidth=1.0)
    axes[0, 1].set_ylim(-0.10, 0.25)
    axes[0, 1].set_title("Required price violates U >= 0")
    axes[0, 1].set_ylabel("Normalized price")
    axes[0, 1].grid(True)
    axes[0, 1].legend(loc="best")

    axes[1, 0].plot(
        hours,
        price_target_state,
        linewidth=2.5,
        label="Target-implied state",
    )
    axes[1, 0].plot(
        hours,
        price_state,
        linestyle="--",
        label="Best admissible state",
    )
    axes[1, 0].axhspan(0.0, 1.0, color="green", alpha=0.08)
    axes[1, 0].set_title("Price target respects state capacity")
    axes[1, 0].set_xlabel("Time [hours]")
    axes[1, 0].set_ylabel("State X")
    axes[1, 0].grid(True)
    axes[1, 0].legend(loc="best")

    axes[1, 1].plot(
        hours,
        capacity_required_state,
        linewidth=2.5,
        label="Target-implied state",
    )
    axes[1, 1].plot(
        hours,
        capacity_state,
        linestyle="--",
        label="Best admissible state",
    )
    axes[1, 1].axhspan(0.0, 1.0, color="green", alpha=0.08)
    axes[1, 1].axhline(1.0, color="black", linewidth=1.0)
    axes[1, 1].set_title(
        f"Capacity target A(t) = {CAPACITY_TARGET:.2f}, "
        f"J = {tracking_objective(OBJECTIVE_T, capacity_demand, capacity_values):.3e}"
    )
    axes[1, 1].set_xlabel("Time [hours]")
    axes[1, 1].set_ylabel("State X")
    axes[1, 1].grid(True)
    axes[1, 1].legend(loc="best")

    fig.tight_layout()
    graph_dir = Path(__file__).resolve().parents[3] / "files" / "output" / "graphs"
    graph_dir.mkdir(parents=True, exist_ok=True)
    graph_path = graph_dir / "BM1_optimization_feasibility_reference.png"
    fig.savefig(graph_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    return graph_path


def main():
    """Run analytical feasibility diagnostics before bounded optimization."""
    baseline = build_baseline()

    # Case 1: state and hold structure are feasible, but the required held
    # price lies below the admissible lower bound.
    target_state = np.asarray(
        price_bound_target_state(OBJECTIVE_T), dtype=float
    )
    target_demand = np.asarray(price_bound_target(OBJECTIVE_T), dtype=float)
    required_price = benchmark_required_price(target_state, target_demand)
    _, maximum_demand = benchmark_demand_envelope(target_state)
    envelope_gap = target_demand - maximum_demand

    price_model = BM1(baseline, price_bound_target, T, OBJECTIVE_T.size)
    price_results = optimize_from_starts(
        price_model,
        PRICE_EDGES,
        PRICE_STARTS,
    )
    price_best = best_result(price_results)
    price_solution = solve_prices(
        price_model,
        PRICE_EDGES,
        price_best.x,
        OBJECTIVE_T,
        RTOL,
        ATOL,
    )
    price_objective = tracking_objective(
        OBJECTIVE_T,
        price_solution[7],
        target_demand,
    )

    fine_solution = solve_prices(
        price_model,
        PRICE_EDGES,
        price_best.x,
        FINE_T,
        FINE_RTOL,
        FINE_ATOL,
        max_step=(T[1] - T[0]) / (FINE_T.size - 1),
    )
    fine_objective = tracking_objective(
        FINE_T,
        fine_solution[7],
        np.asarray(price_bound_target(FINE_T), dtype=float),
    )

    initial_solution = solve_prices(
        price_model,
        PRICE_EDGES,
        np.array([0.5]),
        OBJECTIVE_T,
        RTOL,
        ATOL,
    )
    initial_objective = tracking_objective(
        OBJECTIVE_T,
        initial_solution[7],
        target_demand,
    )

    price_vectors = np.vstack([result.x for result in price_results])
    price_objectives = np.array(
        [result.fun for result in price_results], dtype=float
    )

    # Case 2: the energy-prefix condition itself is violated.  This proves a
    # non-zero lower bound independently of optimizer convergence.
    capacity_values = np.asarray(capacity_target(OBJECTIVE_T), dtype=float)
    capacity_required_state = np.asarray(
        target_implied_state(OBJECTIVE_T, CAPACITY_TARGET), dtype=float
    )
    target_energy = (
        (CAPACITY_TARGET - BASELINE) * (T[1] - T[0])
    )
    upper_capacity = C * (1.0 - X0)
    excess_energy = target_energy - upper_capacity
    objective_lower_bound = excess_energy**2 / (T[1] - T[0])
    capacity_violation_time = (
        T[0] + upper_capacity / (CAPACITY_TARGET - BASELINE)
    )

    capacity_model = BM1(baseline, capacity_target, T, OBJECTIVE_T.size)
    capacity_results = optimize_from_starts(
        capacity_model,
        CAPACITY_EDGES,
        CAPACITY_STARTS,
    )
    capacity_best = best_result(capacity_results)
    capacity_solution = solve_prices(
        capacity_model,
        CAPACITY_EDGES,
        capacity_best.x,
        OBJECTIVE_T,
        RTOL,
        ATOL,
    )
    capacity_objective = tracking_objective(
        OBJECTIVE_T,
        capacity_solution[7],
        capacity_values,
    )
    capacity_fine_solution = solve_prices(
        capacity_model,
        CAPACITY_EDGES,
        capacity_best.x,
        FINE_T,
        FINE_RTOL,
        FINE_ATOL,
        max_step=(T[1] - T[0]) / (FINE_T.size - 1),
    )
    capacity_fine_objective = tracking_objective(
        FINE_T,
        capacity_fine_solution[7],
        np.asarray(capacity_target(FINE_T), dtype=float),
    )
    capacity_objectives = np.array(
        [result.fun for result in capacity_results], dtype=float
    )

    graph_path = save_figure(
        price_best,
        price_solution[1],
        price_solution[7],
        required_price,
        capacity_solution[1],
        capacity_solution[7],
        capacity_required_state,
    )

    checks = {
        "price-bound target demand remains normalized": (
            np.min(target_demand) >= 0.0 and np.max(target_demand) <= 1.0
        ),
        "price-bound target state remains in [0, 1]": (
            np.min(target_state) >= 0.0 and np.max(target_state) <= 1.0
        ),
        "inverse diagnostic recovers the held required price": np.allclose(
            required_price,
            REQUIRED_PRICE,
            rtol=0.0,
            atol=1.0e-10,
        ),
        "required price satisfies the one-interval hold restriction": (
            np.ptp(required_price) <= 1.0e-10
        ),
        "required held price violates the admissible lower bound": (
            np.max(required_price) < 0.0
        ),
        "target exceeds the admissible demand envelope": (
            np.min(envelope_gap) > 0.0
        ),
        "all price-bound multistarts converge": all(
            result.success for result in price_results
        ),
        "price-bound multistarts agree on the boundary solution": (
            np.max(np.ptp(price_vectors, axis=0)) <= 1.0e-8
            and np.ptp(price_objectives) <= 1.0e-10
        ),
        "optimized price is active at the lower bound": (
            price_best.x[0] <= 1.0e-8
        ),
        "price-bound objective is positive and reproducible": (
            5.0e-4 < price_objective < 2.0e-3
            and np.isclose(
                price_best.fun,
                price_objective,
                rtol=1.0e-7,
                atol=1.0e-12,
            )
        ),
        "fine-grid recomputation agrees": np.isclose(
            fine_objective,
            price_objective,
            rtol=1.0e-6,
            atol=1.0e-12,
        ),
        "bounded optimization improves the initial price": (
            price_objective < initial_objective / 100.0
        ),
        "best price-bound state remains in [0, 1]": (
            np.min(price_solution[1]) >= -1.0e-12
            and np.max(price_solution[1]) <= 1.0 + 1.0e-12
        ),
        "capacity target violates the upper state bound": (
            capacity_required_state[-1] > 1.0
        ),
        "capacity violation occurs inside the model horizon": (
            T[0] < capacity_violation_time < T[1]
        ),
        "capacity certificate has positive excess energy": (
            excess_energy > 0.0 and objective_lower_bound > 0.0
        ),
        "all capacity-case multistarts converge": all(
            result.success for result in capacity_results
        ),
        "capacity-case multistarts agree on the objective": (
            np.ptp(capacity_objectives) <= 1.0e-9
        ),
        "reported and recomputed capacity objectives agree": np.isclose(
            capacity_best.fun,
            capacity_objective,
            rtol=1.0e-7,
            atol=1.0e-12,
        ),
        "capacity fine-grid recomputation agrees": np.isclose(
            capacity_fine_objective,
            capacity_objective,
            rtol=1.0e-3,
            atol=1.0e-10,
        ),
        "capacity objective respects the analytical lower bound": (
            capacity_objective >= objective_lower_bound - 1.0e-10
        ),
        "best capacity-case state remains in [0, 1]": (
            np.min(capacity_solution[1]) >= -1.0e-12
            and np.max(capacity_solution[1]) <= 1.0 + 1.0e-12
        ),
        "reference figure is saved": (
            graph_path.is_file() and graph_path.stat().st_size > 0
        ),
    }

    print("BM1 deterministic optimization F1-E feasibility verification")
    print("============================================================")
    print()
    print("Price-bound certificate")
    print(f"required held price       = {REQUIRED_PRICE:.6f}")
    print(f"target state range        = [{np.min(target_state):.6f}, "
          f"{np.max(target_state):.6f}]")
    print(f"target demand range       = [{np.min(target_demand):.6f}, "
          f"{np.max(target_demand):.6f}]")
    print(f"minimum envelope gap      = {np.min(envelope_gap):.6e}")
    print(f"optimized admissible price = {price_best.x}")
    print(f"initial objective (U=.5)  = {initial_objective:.6e}")
    print(f"optimized objective       = {price_objective:.6e}")
    print(f"fine-grid objective       = {fine_objective:.6e}")
    print()
    print("Capacity certificate")
    print(f"constant target demand    = {CAPACITY_TARGET:.6f}")
    print(f"required final state      = {capacity_required_state[-1]:.6f}")
    print(f"capacity violation time   = {24.0 * capacity_violation_time:.6f} hours")
    print(f"target excess energy      = {excess_energy:.6e}")
    print(f"objective lower bound     = {objective_lower_bound:.6e}")
    print(f"optimized prices          = {capacity_best.x}")
    print(f"optimized objective       = {capacity_objective:.6e}")
    print(f"fine-grid objective       = {capacity_fine_objective:.6e}")
    print()
    print("Checks")
    for name, passed in checks.items():
        print(f"{'PASS' if passed else 'FAIL'} {name}")
    print()
    print(f"Saved graph to {graph_path}")

    failed = [name for name, passed in checks.items() if not passed]
    if failed:
        print()
        print("One or more F1-E checks failed:")
        for name in failed:
            print(f"- {name}")
        raise SystemExit(1)


if __name__ == "__main__":
    main()
